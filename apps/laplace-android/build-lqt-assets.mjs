import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const base=fileURLToPath(new URL('.',import.meta.url)),assets=base+'app/src/main/assets/';
const hash=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
const kernel=hash(base+'app/src/main/cpp/laplace_temporal.hpp'),template=hash(assets+'lqt1000-native.xi');
const report=JSON.parse(readFileSync(base+'../../evidencia/lqt1000/resultados.json','utf8'));
if(report.algorithmSHA256!==kernel)throw Error('Repite el estudio nativo LQT: cambió el algoritmo.');
const java='package com.entidadlaplace.mobile;\n/** Generated by build-lqt-assets.mjs; do not edit. */\n'+
 'public final class LQTBuild {\n    private LQTBuild(){}\n'+
 `    public static final String KERNEL_SHA256="${kernel}";\n`+
 `    public static final String TEMPLATE_SHA256="${template}";\n}\n`;
const evidence={schema:'laplace-lqt-release-v1',kernelSHA256:kernel,templateSHA256:template,
 qubits:1000,components:1,trainableRotations:1000,source:report.source,
 sourceSHA256:report.sourceSHA256,rows:report.rows,protocol:report.protocol,
 nativeVerification:report.nativeVerification,retention:report.retention,
 horizons:report.horizons.map(h=>({minutes:h.minutes,quantum:h.quantum.test,matchedClassical:h.matchedClassical.test})),
 prospectivelyValidated:false,physicalQPU:false};
for(const [path,content]of [[base+'app/src/main/java/com/entidadlaplace/mobile/LQTBuild.java',java],
 [assets+'lqt-evidence.js','window.LAPLACE_LQT_RELEASE = '+JSON.stringify(evidence)+';\n']]){
 if(process.argv.includes('--verify')){if(readFileSync(path,'utf8')!==content)throw Error('LQT generado desactualizado: '+path);}
 else writeFileSync(path,content);
}
